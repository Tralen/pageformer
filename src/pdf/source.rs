//! Converts the document model into Typst source.
//!
//! The conversion is pure. User text is escaped for Typst markup and user
//! strings for Typst string literals, so the generated source can only describe
//! layout the project controls.

use std::collections::BTreeMap;
use std::fmt::Write;

use crate::document::{
    Block, CodeBlock, ColumnAlignment, Document, Inline, Language, List, ListItem, ListStart,
    QuoteKind, Table, TaskState,
};
use crate::template::{
    BlockStyle, Color, HeadingStyle, InlineStyle, Length, LinkStyle, ListStyle, ParagraphAlignment,
    PartialTextStyle, RuleStyle, RunningText, TableStyle, TaskMarkerStyle, Template, TextFace,
    is_lowercase_token,
};

use super::assets::AssetMap;
use super::{FIXED_DAY, FIXED_MONTH, FIXED_YEAR, PdfError};

/// Builds the Typst source for a document and a template.
pub fn typst_source(
    document: &Document,
    template: &Template,
    assets: &AssetMap,
) -> Result<String, PdfError> {
    let mut builder = SourceBuilder::new(document, template, assets);
    builder.preamble(document, template);
    builder.heading_style(template);
    builder.blocks(document.blocks())?;
    Ok(builder.output)
}

struct SourceBuilder<'a> {
    output: String,
    assets: &'a AssetMap,
    table: &'a TableStyle,
    rule: &'a RuleStyle,
    list: &'a ListStyle,
    list_fill: Option<Color>,
    list_fill_padding: f64,
    list_fill_outset: f64,
    list_depth: usize,
    paragraph_fill: Option<Color>,
    paragraph_spacing: String,
    nested: bool,
    footnotes: BTreeMap<String, Vec<Block>>,
    footnote_stack: Vec<String>,
}

impl<'a> SourceBuilder<'a> {
    fn new(document: &Document, template: &'a Template, assets: &'a AssetMap) -> Self {
        let mut footnotes = BTreeMap::new();
        collect_footnotes(document.blocks(), &mut footnotes);
        let list = template.formatting().list();
        let list_fill = list.text().background();
        let list_fill_padding = list
            .text()
            .size()
            .unwrap_or_else(|| template.formatting().paragraph().face().size())
            .points()
            * FILL_PADDING;
        let list_fill_outset = template.formatting().paragraph().leading().points();
        Self {
            output: String::new(),
            assets,
            table: template.table(),
            rule: template.formatting().horizontal_rule(),
            list,
            list_fill,
            list_fill_padding,
            list_fill_outset,
            list_depth: 0,
            paragraph_fill: template.formatting().paragraph().background(),
            paragraph_spacing: template
                .formatting()
                .paragraph()
                .spacing()
                .map_or_else(|| "1.2em".to_owned(), typst_length),
            nested: false,
            footnotes,
            footnote_stack: Vec::new(),
        }
    }

    fn preamble(&mut self, document: &Document, template: &Template) {
        self.output.push_str("// Generated by pageformer.\n\n");
        self.output.push_str("#set document(\n");
        if let Some(title) = document.metadata().title() {
            let _ = writeln!(self.output, "  title: {},", typst_string(title.as_str()));
        }
        if let Some(author) = document.metadata().author() {
            let _ = writeln!(self.output, "  author: {},", typst_string(author.as_str()));
        }
        if let Some(subject) = document.metadata().subject() {
            let _ = writeln!(
                self.output,
                "  description: {},",
                typst_string(subject.as_str())
            );
        }
        if !document.metadata().keywords().is_empty() {
            self.output.push_str("  keywords: (");
            for keyword in document.metadata().keywords() {
                let _ = write!(self.output, "{}, ", typst_string(keyword.as_str()));
            }
            self.output.push_str("),\n");
        }
        let date = document.metadata().date();
        let (year, month, day) = match date {
            Some(date) => (date.year(), date.month(), date.day()),
            None => (FIXED_YEAR, FIXED_MONTH, FIXED_DAY),
        };
        let _ = writeln!(
            self.output,
            "  date: datetime(year: {year}, month: {month}, day: {day}),"
        );
        self.output.push_str(")\n\n");

        let page = template.page();
        let dimensions = page.dimensions();
        self.output.push_str("#set page(\n");
        let _ = writeln!(
            self.output,
            "  width: {},",
            typst_length(dimensions.width())
        );
        let _ = writeln!(
            self.output,
            "  height: {},",
            typst_length(dimensions.height())
        );
        let margins = page.margins();
        let _ = writeln!(
            self.output,
            "  margin: (top: {}, bottom: {}, left: {}, right: {}),",
            typst_length(margins.top()),
            typst_length(margins.bottom()),
            typst_length(margins.left()),
            typst_length(margins.right()),
        );
        if let Some(letterhead) = self.assets.letterhead() {
            let _ = writeln!(
                self.output,
                "  background: image({}, width: 100%),",
                typst_string(letterhead)
            );
        }
        if let Some(header) = page.header() {
            self.running("header", header, document, template);
        }
        if let Some(footer) = page.footer() {
            self.running("footer", footer, document, template);
        }
        self.output.push_str(")\n\n");

        let language = document.metadata().language();
        let paragraph = template.formatting().paragraph();
        let face = paragraph.face();
        self.output.push_str("#set text(\n  font: (");
        for family in face.font_families() {
            let _ = write!(self.output, "{}, ", typst_string(family.as_str()));
        }
        self.output.push_str("),\n");
        let _ = writeln!(self.output, "  size: {},", typst_length(face.size()));
        let _ = writeln!(self.output, "  weight: {},", face.weight().get());
        let _ = writeln!(
            self.output,
            "  style: {},",
            typst_string(face.slant().as_str())
        );
        if let Some(foreground) = face.foreground() {
            let _ = writeln!(self.output, "  fill: rgb(\"{}\"),", foreground.hex());
        }
        if let Some(language) = language {
            self.language_rules(language);
        }
        self.output.push_str(")\n\n");

        let justify = matches!(paragraph.alignment(), ParagraphAlignment::Justified);
        let _ = write!(
            self.output,
            "#set par(justify: {justify}, leading: {}",
            typst_length(paragraph.leading())
        );
        if let Some(spacing) = paragraph.spacing() {
            let _ = write!(self.output, ", spacing: {}", typst_length(spacing));
        }
        self.output.push_str(")\n\n");

        self.inline_style("emph", paragraph.emphasis());
        self.inline_style("strong", paragraph.strong());

        self.inline_partial("raw.where(block: false)", paragraph.code());
        self.inline_partial("strike", paragraph.strikethrough());
        self.link_style(paragraph.link());
        self.block_style("quote.where(block: true)", template.formatting().quote());
        self.block_style("raw.where(block: true)", template.formatting().code_block());
        self.list_style(template.formatting().list());
        self.output.push('\n');
    }

    /// Applies the declared keys of an inline style, leaving the rest untouched.
    fn inline_partial(&mut self, selector: &str, style: &PartialTextStyle) {
        self.text_partial(selector, style);
        if let Some(background) = style.background() {
            let _ = writeln!(
                self.output,
                "#show {selector}: it => box(fill: rgb(\"{}\"), inset: 0pt)[#it]",
                background.hex()
            );
        }
    }

    /// Applies the list text face, alignment, marker layout, bullets and the
    /// numbering pattern to both list kinds.
    fn list_style(&mut self, list: &ListStyle) {
        self.text_partial("list.item", list.text());
        self.text_partial("enum.item", list.text());
        let justify = matches!(list.alignment(), ParagraphAlignment::Justified);
        let _ = writeln!(self.output, "#show list.item: set par(justify: {justify})");
        let _ = writeln!(self.output, "#show enum.item: set par(justify: {justify})");
        let indent = typst_length(list.indent());
        let body_indent = typst_length(list.marker_gap());
        let mut markers = String::from("(");
        for bullet in list.bullets() {
            let _ = write!(markers, "[{}], ", escape_markup(bullet));
        }
        markers.push(')');
        let _ = writeln!(
            self.output,
            "#set list(indent: {indent}, body-indent: {body_indent}, marker: {markers})"
        );
        let mut pattern = String::new();
        for depth in 0..10 {
            pattern.push(list.numbering_format(depth).typst_symbol());
            pattern.push_str(list.suffix());
        }
        let _ = writeln!(
            self.output,
            "#set enum(indent: {indent}, body-indent: {body_indent}, numbering: {})",
            typst_string(&pattern)
        );
    }

    /// Applies the link decoration: the face, the optional fill, the color and
    /// the underline the template declares.
    fn link_style(&mut self, link: &LinkStyle) {
        self.text_partial("link", link.text());
        let mut body = String::from("it");
        if let Some(background) = link.text().background() {
            body = format!(
                "highlight(fill: rgb(\"{}\"), extent: 0pt, {body})",
                background.hex()
            );
        }
        if link.underline() {
            body = format!("underline({body})");
        }
        if body != "it" {
            let _ = writeln!(self.output, "#show link: it => {body}");
        }
    }

    /// Applies a block style: text, alignment, and a wrapper that carries the
    /// fill, the border and the padding of the bordered sides. A fill adds the
    /// font-box padding on the top and bottom, the same way a heading fill does,
    /// so the text does not touch the edges of the band.
    fn block_style(&mut self, selector: &str, style: &BlockStyle) {
        self.text_partial(selector, style.text());
        let justify = matches!(style.alignment(), ParagraphAlignment::Justified);
        let _ = writeln!(self.output, "#show {selector}: set par(justify: {justify})");
        let border = style.border();
        let fill_inset = match style.text().background() {
            Some(_) => style
                .text()
                .size()
                .map_or(0.0, |size| size.points() * FILL_PADDING),
            None => 0.0,
        };
        let mut arguments = Vec::new();
        if let Some(background) = style.text().background() {
            arguments.push(format!("fill: rgb(\"{}\")", background.hex()));
        }
        let mut strokes = Vec::new();
        let mut insets = Vec::new();
        for (side, thickness) in [
            ("left", border.left()),
            ("right", border.right()),
            ("top", border.top()),
            ("bottom", border.bottom()),
        ] {
            let border_padding = match thickness {
                Some(thickness) => {
                    strokes.push(format!(
                        "{side}: {} + rgb(\"{}\")",
                        typst_length(thickness),
                        border.color().hex()
                    ));
                    border.padding().points()
                }
                None => 0.0,
            };
            let padding = match side {
                "top" | "bottom" => border_padding.max(fill_inset),
                _ => border_padding,
            };
            if padding > 0.0 {
                insets.push(format!("{side}: {padding:.3}pt"));
            }
        }
        if !strokes.is_empty() {
            arguments.push(format!("stroke: ({})", strokes.join(", ")));
        }
        if !insets.is_empty() {
            arguments.push(format!("inset: ({})", insets.join(", ")));
        }
        if !arguments.is_empty() {
            let _ = writeln!(
                self.output,
                "#show {selector}: it => block(width: 100%, {})[#it]",
                arguments.join(", ")
            );
        }
    }

    fn text_partial(&mut self, selector: &str, style: &PartialTextStyle) {
        let properties = text_arguments(style);
        if !properties.is_empty() {
            let _ = writeln!(
                self.output,
                "#show {selector}: set text({})",
                properties.join(", ")
            );
        }
    }

    fn language_rules(&mut self, language: &Language) {
        let (primary, region) = split_language(language.as_str());
        let _ = writeln!(self.output, "  lang: {},", typst_string(primary));
        if let Some(region) = region {
            let _ = writeln!(self.output, "  region: {},", typst_string(region));
        }
    }

    fn inline_style(&mut self, element: &str, inline: &InlineStyle) {
        let face = inline.face();
        let _ = write!(self.output, "#show {element}: set text(font: (");
        for family in face.font_families() {
            let _ = write!(self.output, "{}, ", typst_string(family.as_str()));
        }
        let _ = writeln!(
            self.output,
            "), size: {}, weight: {}, style: {}{})",
            typst_length(face.size()),
            face.weight().get(),
            typst_string(face.slant().as_str()),
            fill_argument(face)
        );
        if let Some(background) = inline.background() {
            let _ = writeln!(
                self.output,
                "#show {element}: it => highlight(fill: rgb(\"{}\"), extent: 0pt, it)",
                background.hex()
            );
        }
    }

    fn running(
        &mut self,
        name: &str,
        running: &RunningText,
        document: &Document,
        template: &Template,
    ) {
        let face = template.formatting().paragraph().face();
        let _ = writeln!(self.output, "  {name}: [");
        self.output.push_str("    #set text(font: (");
        for family in face.font_families() {
            let _ = write!(self.output, "{}, ", typst_string(family.as_str()));
        }
        let _ = writeln!(
            self.output,
            "), size: {}, weight: {}, style: {}{})",
            typst_length(face.size()),
            face.weight().get(),
            typst_string(face.slant().as_str()),
            fill_argument(face)
        );
        self.output
            .push_str("    #grid(columns: (1fr, 1fr, 1fr), align: (left, center, right),\n");
        for slot in [
            running.slots().left(),
            running.slots().center(),
            running.slots().right(),
        ] {
            self.output.push_str("      ");
            self.output.push('[');
            if let Some(text) = slot {
                self.running_text(text, document);
            }
            self.output.push_str("],\n");
        }
        self.output.push_str("    )\n  ],\n");
    }

    /// Expands the lowercase tokens of a running slot and escapes the rest.
    fn running_text(&mut self, text: &str, document: &Document) {
        let mut rest = text;
        while let Some((before, after)) = rest.split_once('{') {
            self.output.push_str(&escape_markup(before));
            match after.split_once('}') {
                Some((token, remaining)) if is_lowercase_token(token) => {
                    match token {
                        "page" => self.output.push_str("#context counter(page).display()"),
                        "pages" => {
                            self.output
                                .push_str("#context counter(page).final().first()");
                        }
                        "title" => {
                            if let Some(title) = document.metadata().title() {
                                self.output.push_str(&escape_markup(title.as_str()));
                            }
                        }
                        "author" => {
                            if let Some(author) = document.metadata().author() {
                                self.output.push_str(&escape_markup(author.as_str()));
                            }
                        }
                        other => {
                            self.output
                                .push_str(&escape_markup(&format!("{{{other}}}")));
                        }
                    }
                    rest = remaining;
                }
                Some((token, remaining)) => {
                    self.output
                        .push_str(&escape_markup(&format!("{{{token}}}")));
                    rest = remaining;
                }
                None => {
                    self.output.push_str(&escape_markup("{"));
                    rest = after;
                }
            }
        }
        self.output.push_str(&escape_markup(rest));
    }

    fn heading_style(&mut self, template: &Template) {
        for (index, style) in template.formatting().heading().levels().iter().enumerate() {
            let level = index + 1;
            let face = style.face();
            let _ = write!(
                self.output,
                "#show heading.where(level: {level}): set text(font: ("
            );
            for family in face.font_families() {
                let _ = write!(self.output, "{}, ", typst_string(family.as_str()));
            }
            let _ = writeln!(
                self.output,
                "), size: {}, weight: {}, style: {}{})",
                typst_length(face.size()),
                face.weight().get(),
                typst_string(face.slant().as_str()),
                fill_argument(face)
            );
            if style.background().is_some() || style.rule().is_some() {
                // The wrapper carries the heading spacing, so the text inside it keeps none.
                // The rule's own spacing_after, when declared, replaces the heading's below.
                let below = style
                    .rule()
                    .and_then(RuleStyle::spacing_after)
                    .unwrap_or(style.spacing_after());
                let _ = writeln!(
                    self.output,
                    "#show heading.where(level: {level}): set block(above: 0pt, below: 0pt)"
                );
                let _ = writeln!(
                    self.output,
                    "#show heading.where(level: {level}): it => block(width: 100%, above: {}, below: {}, sticky: true)[\n{}\n]",
                    typst_length(style.spacing_before()),
                    typst_length(below),
                    heading_content(style)
                );
            } else {
                let _ = writeln!(
                    self.output,
                    "#show heading.where(level: {level}): set block(above: {}, below: {})",
                    typst_length(style.spacing_before()),
                    typst_length(style.spacing_after())
                );
            }
            if style.page_break_before() {
                let _ = writeln!(
                    self.output,
                    "#show heading.where(level: {level}): it => {{\n  pagebreak(weak: true)\n  it\n}}"
                );
            }
        }
        self.output.push('\n');
    }

    /// Opens a paragraph, adding the body fill when the template declares one.
    /// Quotes and lists keep their own background.
    fn open_paragraph(&mut self) {
        if !self.nested && self.paragraph_fill.is_some() {
            let spacing = self.paragraph_spacing.clone();
            if let Some(fill) = self.paragraph_fill {
                let _ = write!(
                    self.output,
                    "#block(width: 100%, fill: rgb(\"{}\"), inset: 0pt, above: {spacing}, below: {spacing})[",
                    fill.hex()
                );
            }
        }
        self.output.push_str("#par[");
    }

    fn close_paragraph(&mut self) {
        self.output.push(']');
        if !self.nested && self.paragraph_fill.is_some() {
            self.output.push(']');
        }
    }

    fn blocks(&mut self, blocks: &[Block]) -> Result<(), PdfError> {
        for block in blocks {
            self.block(block)?;
            self.output.push_str("\n\n");
        }
        Ok(())
    }

    fn block(&mut self, block: &Block) -> Result<(), PdfError> {
        match block {
            Block::Heading(heading) => {
                let _ = write!(self.output, "#heading(level: {})[", heading.level().get());
                self.inlines(heading.content())?;
                self.output.push(']');
            }
            Block::Paragraph(inlines) => {
                self.open_paragraph();
                self.inlines(inlines)?;
                self.close_paragraph();
            }
            Block::NumberedParagraph(paragraph) => {
                self.open_paragraph();
                self.output
                    .push_str(&escape_markup(&format!("{}. ", paragraph.number())));
                self.inlines(paragraph.content())?;
                self.close_paragraph();
            }
            Block::List(list) => self.list(list)?,
            Block::Table(table) => self.table(table)?,
            Block::Quote(quote) => {
                self.output.push_str("#quote(block: true)[\n");
                let nested = std::mem::replace(&mut self.nested, true);
                if let QuoteKind::Alert(alert) = quote.kind() {
                    self.block(&Block::Paragraph(vec![Inline::Text(format!(
                        "[{}]",
                        alert.label()
                    ))]))?;
                    self.output.push_str("\n\n");
                }
                self.blocks(quote.blocks())?;
                self.nested = nested;
                self.output.push(']');
            }
            Block::CodeBlock(code) => self.code_block(code),
            Block::ThematicBreak => self.thematic_break(),
            Block::PageBreak => self.output.push_str("#pagebreak()"),
            Block::FootnoteDefinition(_) => {}
        }
        Ok(())
    }

    fn inlines(&mut self, inlines: &[Inline]) -> Result<(), PdfError> {
        for inline in inlines {
            self.inline(inline)?;
        }
        Ok(())
    }

    fn inline(&mut self, inline: &Inline) -> Result<(), PdfError> {
        match inline {
            Inline::Text(text) => self.output.push_str(&escape_markup(text)),
            Inline::Code(code) => {
                self.output.push_str("#raw(");
                self.output.push_str(&typst_string(code));
                self.output.push_str(", block: false)");
            }
            Inline::Emphasis(content) => self.wrapped("emph", content)?,
            Inline::Strong(content) => self.wrapped("strong", content)?,
            Inline::Strikethrough(content) => self.wrapped("strike", content)?,
            Inline::Link {
                destination,
                content,
                ..
            } => {
                if destination.as_str().is_empty() {
                    self.inlines(content)?;
                } else {
                    let _ = write!(
                        self.output,
                        "#link({})[",
                        typst_string(destination.as_str())
                    );
                    self.inlines(content)?;
                    self.output.push(']');
                }
            }
            Inline::Image {
                destination,
                alternative,
                ..
            } => {
                let asset = self.assets.image(destination.as_str()).ok_or_else(|| {
                    PdfError::MissingAsset {
                        destination: destination.as_str().to_owned(),
                    }
                })?;
                let _ = write!(self.output, "#box(image({}", typst_string(asset));
                let alternative = plain_text(alternative);
                if !alternative.is_empty() {
                    let _ = write!(self.output, ", alt: {}", typst_string(&alternative));
                }
                self.output.push_str("))");
            }
            Inline::SoftBreak => self.output.push(' '),
            Inline::HardBreak => self.output.push_str("#linebreak()"),
            Inline::FootnoteReference(id) => {
                let active = self.footnote_stack.iter().any(|name| name == id.as_str());
                let definition = if active {
                    None
                } else {
                    self.footnotes.get(id.as_str()).cloned()
                };
                match definition {
                    Some(blocks) => {
                        self.footnote_stack.push(id.as_str().to_owned());
                        self.output.push_str("#footnote[\n");
                        let rendered = self.blocks(&blocks);
                        self.output.push(']');
                        self.footnote_stack.pop();
                        rendered?;
                    }
                    None => {
                        self.output
                            .push_str(&escape_markup(&format!("[^{}]", id.as_str())));
                    }
                }
            }
        }
        Ok(())
    }

    fn wrapped(&mut self, function: &str, content: &[Inline]) -> Result<(), PdfError> {
        let _ = write!(self.output, "#{function}[");
        self.inlines(content)?;
        self.output.push(']');
        Ok(())
    }

    fn list(&mut self, list: &List) -> Result<(), PdfError> {
        if list.items().is_empty() {
            return Ok(());
        }
        let spacing = if list.is_tight() {
            String::new()
        } else {
            self.list.spacing().map_or_else(String::new, |spacing| {
                format!(", spacing: {}", typst_length(spacing))
            })
        };
        match list.start() {
            ListStart::Unordered => {
                let suppress_bullet = !self.list.task().bullet() && list.is_task_list();
                let marker = if suppress_bullet {
                    ", marker: [], body-indent: 0pt"
                } else {
                    ""
                };
                let _ = writeln!(
                    self.output,
                    "#list(tight: {}{spacing}{marker},",
                    list.is_tight()
                );
            }
            ListStart::Ordered(start) => {
                let _ = writeln!(
                    self.output,
                    "#enum(tight: {}, start: {start}{spacing},",
                    list.is_tight()
                );
            }
        }
        let outer = std::mem::replace(&mut self.nested, true);
        let nested_list = self.list_depth > 0;
        self.list_depth = self.list_depth.saturating_add(1);
        let count = list.items().len();
        for (index, item) in list.items().iter().enumerate() {
            self.output.push_str("  [");
            let first = index == 0 && !nested_list;
            let last = index.saturating_add(1) == count && !nested_list;
            self.item(item, list.is_tight(), first, last)?;
            self.output.push_str("],\n");
        }
        self.list_depth = self.list_depth.saturating_sub(1);
        self.nested = outer;
        self.output.push(')');
        Ok(())
    }

    /// Renders one list item. A declared background fills the first paragraph
    /// and the task marker, not the marker column or a nested list. In a tight
    /// list the fill outgrows the item into the gap between items, so adjacent
    /// bands meet the way the office paragraph shading does.
    fn item(
        &mut self,
        item: &ListItem,
        tight: bool,
        first: bool,
        last: bool,
    ) -> Result<(), PdfError> {
        if let Some(fill) = self.list_fill
            && let Some(Block::Paragraph(inlines)) = item.blocks().first()
        {
            let outset = if tight {
                let top = if first { 0.0 } else { self.list_fill_outset };
                let bottom = if last { 0.0 } else { self.list_fill_outset };
                if top > 0.0 || bottom > 0.0 {
                    format!(", outset: (top: {top:.3}pt, bottom: {bottom:.3}pt)")
                } else {
                    String::new()
                }
            } else {
                String::new()
            };
            let _ = write!(
                self.output,
                "#block(width: 100%, fill: rgb(\"{}\"), inset: (x: 0pt, y: {:.3}pt){outset})[",
                fill.hex(),
                self.list_fill_padding
            );
            self.task_marker(item.task());
            self.inlines(inlines)?;
            self.output.push(']');
            if let Some(rest) = item.blocks().get(1..) {
                self.blocks(rest)?;
            }
            return Ok(());
        }
        self.task_marker(item.task());
        self.item_blocks(item.blocks())
    }

    fn task_marker(&mut self, task: Option<TaskState>) {
        let Some(state) = task else {
            return;
        };
        let task_style = self.list.task();
        let marker = match state {
            TaskState::Done => task_style.done(),
            TaskState::Todo => task_style.todo(),
        };
        self.output.push_str(&task_marker_content(marker));
        for _ in 0..task_style.gap() {
            self.output.push('\u{a0}');
        }
    }

    fn item_blocks(&mut self, blocks: &[Block]) -> Result<(), PdfError> {
        match blocks {
            [Block::Paragraph(inlines)] => self.inlines(inlines),
            _ => self.blocks(blocks),
        }
    }

    fn table(&mut self, table: &Table) -> Result<(), PdfError> {
        let _ = writeln!(
            self.output,
            "#table(\n  columns: {},",
            table.alignments().len()
        );
        self.output.push_str("  align: (");
        for alignment in table.alignments() {
            let _ = write!(self.output, "{}, ", alignment_name(*alignment));
        }
        let _ = writeln!(
            self.output,
            "),\n  inset: {},",
            typst_length(self.table.cell_padding())
        );
        if self.table.border().points() > 0.0 {
            let _ = writeln!(
                self.output,
                "  stroke: {} + rgb(\"{}\"),",
                typst_length(self.table.border()),
                self.table.border_color().hex()
            );
        } else {
            self.output.push_str("  stroke: none,\n");
        }
        self.output.push_str("  table.header(");
        for cell in table.header() {
            match self.table.header_fill() {
                Some(color) => {
                    let _ = write!(self.output, "table.cell(fill: rgb(\"{}\"))[", color.hex());
                    self.inlines(cell.content())?;
                    self.output.push_str("], ");
                }
                None => {
                    self.output.push('[');
                    self.inlines(cell.content())?;
                    self.output.push_str("], ");
                }
            }
        }
        self.output.push_str("),\n");
        for row in table.rows() {
            self.output.push_str("  ");
            for cell in row {
                self.output.push('[');
                self.inlines(cell.content())?;
                self.output.push_str("], ");
            }
            self.output.push('\n');
        }
        self.output.push(')');
        Ok(())
    }

    fn thematic_break(&mut self) {
        let rule = self.rule;
        let line = rule_line(rule);
        if rule.spacing_before().is_none() && rule.spacing_after().is_none() {
            self.output.push_str(&line);
        } else {
            let _ = write!(
                self.output,
                "#block(width: 100%, above: {}, below: {})[{line}]",
                optional_length(rule.spacing_before()),
                optional_length(rule.spacing_after())
            );
        }
    }

    fn code_block(&mut self, code: &CodeBlock) {
        self.output.push_str("#raw(");
        self.output.push_str(&typst_string(code.text()));
        if let Some(language) = code.language() {
            let _ = write!(self.output, ", lang: {}", typst_string(language.as_str()));
        }
        self.output.push_str(", block: true)");
    }
}

fn collect_footnotes(blocks: &[Block], footnotes: &mut BTreeMap<String, Vec<Block>>) {
    for block in blocks {
        match block {
            Block::FootnoteDefinition(definition) => {
                footnotes
                    .entry(definition.id().as_str().to_owned())
                    .or_insert_with(|| definition.blocks().to_vec());
                collect_footnotes(definition.blocks(), footnotes);
            }
            Block::List(list) => {
                for item in list.items() {
                    collect_footnotes(item.blocks(), footnotes);
                }
            }
            Block::Quote(quote) => collect_footnotes(quote.blocks(), footnotes),
            Block::Heading(_)
            | Block::Paragraph(_)
            | Block::NumberedParagraph(_)
            | Block::Table(_)
            | Block::CodeBlock(_)
            | Block::ThematicBreak
            | Block::PageBreak => {}
        }
    }
}

fn plain_text(inlines: &[Inline]) -> String {
    let mut text = String::new();
    for inline in inlines {
        match inline {
            Inline::Text(value) | Inline::Code(value) => text.push_str(value),
            Inline::Emphasis(content)
            | Inline::Strong(content)
            | Inline::Strikethrough(content) => text.push_str(&plain_text(content)),
            Inline::Link { content, .. } => text.push_str(&plain_text(content)),
            Inline::Image { alternative, .. } => text.push_str(&plain_text(alternative)),
            Inline::SoftBreak | Inline::HardBreak => text.push(' '),
            Inline::FootnoteReference(id) => {
                let _ = write!(text, "[^{}]", id.as_str());
            }
        }
    }
    text
}

fn split_language(language: &str) -> (&str, Option<&str>) {
    match language.split_once('-') {
        Some((primary, region)) if is_region(region) => (primary, Some(region)),
        Some((primary, _)) => (primary, None),
        None => (language, None),
    }
}

fn is_region(value: &str) -> bool {
    value.len() == 2
        && value
            .chars()
            .all(|character| character.is_ascii_alphabetic())
}

fn alignment_name(alignment: ColumnAlignment) -> &'static str {
    match alignment {
        ColumnAlignment::Default => "auto",
        ColumnAlignment::Left => "left",
        ColumnAlignment::Center => "center",
        ColumnAlignment::Right => "right",
    }
}

fn typst_length(length: Length) -> String {
    format!("{:.3}pt", length.points())
}

fn fill_argument(face: &TextFace) -> String {
    face.foreground().map_or_else(String::new, |color| {
        format!(", fill: rgb(\"{}\")", color.hex())
    })
}

/// The Typst `text` arguments for the declared keys of a partial style.
fn text_arguments(style: &PartialTextStyle) -> Vec<String> {
    let mut arguments = Vec::new();
    if let Some(families) = style.font_families() {
        let mut list = String::from("(");
        for family in families {
            let _ = write!(list, "{}, ", typst_string(family.as_str()));
        }
        list.push(')');
        arguments.push(format!("font: {list}"));
    }
    if let Some(size) = style.size() {
        arguments.push(format!("size: {}", typst_length(size)));
    }
    if let Some(weight) = style.weight() {
        arguments.push(format!("weight: {}", weight.get()));
    }
    if let Some(slant) = style.slant() {
        arguments.push(format!("style: {}", typst_string(slant.as_str())));
    }
    if let Some(foreground) = style.foreground() {
        arguments.push(format!("fill: rgb(\"{}\")", foreground.hex()));
    }
    arguments
}

/// The inline Typst content of a task marker, with only its declared overrides.
fn task_marker_content(marker: &TaskMarkerStyle) -> String {
    let mut content = escape_markup(marker.marker());
    if let Some(background) = marker.text().background() {
        content = format!(
            "#box(fill: rgb(\"{}\"), inset: 0pt)[{content}]",
            background.hex()
        );
    }
    let arguments = text_arguments(marker.text());
    if !arguments.is_empty() {
        content = format!("#text({})[{content}]", arguments.join(", "));
    }
    content
}

fn optional_length(length: Option<Length>) -> String {
    length.map_or_else(|| "auto".to_owned(), typst_length)
}

fn rule_line(rule: &RuleStyle) -> String {
    format!(
        "#line(length: 100%, stroke: {} + rgb(\"{}\"))",
        typst_length(rule.thickness()),
        rule.color().hex()
    )
}

/// The vertical padding of a heading fill, as a fraction of the heading size.
///
/// Typst measures a zero-inset block by its cap height and baseline, about 0.667
/// of the size, while the DOCX fill covers the font's line box, about 1.15 of
/// the size. The padding of 0.24 on each side makes the PDF band match the DOCX
/// one, which is the reference for the other formats. Headings and block fills
/// share it.
const FILL_PADDING: f64 = 0.24;

fn fill_padding(size: Length) -> String {
    format!("{:.3}pt", size.points() * FILL_PADDING)
}

/// The text of a styled heading, with its fill and the rule drawn below it.
fn heading_content(style: &HeadingStyle) -> String {
    let text = match style.background() {
        Some(background) => format!(
            "#block(width: 100%, fill: rgb(\"{}\"), inset: (x: 0pt, y: {}))[#it]",
            background.hex(),
            fill_padding(style.face().size())
        ),
        None => "#it".to_owned(),
    };
    match style.rule() {
        Some(rule) => format!(
            "{text}\n#block(width: 100%, above: {}, below: 0pt)[{}]",
            rule.spacing_before()
                .map_or_else(|| "0pt".to_owned(), typst_length),
            rule_line(rule)
        ),
        None => text,
    }
}

fn escape_markup(text: &str) -> String {
    let mut escaped = String::with_capacity(text.len());
    for character in text.chars() {
        if matches!(
            character,
            '\\' | '#'
                | '$'
                | '*'
                | '_'
                | '`'
                | '<'
                | '>'
                | '@'
                | '~'
                | '['
                | ']'
                | '-'
                | '+'
                | '/'
                | '='
                | ':'
                | '&'
                | '{'
                | '}'
                | '.'
        ) {
            escaped.push('\\');
        }
        escaped.push(character);
    }
    escaped
}

fn typst_string(text: &str) -> String {
    let mut quoted = String::with_capacity(text.len() + 2);
    quoted.push('"');
    for character in text.chars() {
        match character {
            '\\' => quoted.push_str("\\\\"),
            '"' => quoted.push_str("\\\""),
            '\n' => quoted.push_str("\\n"),
            '\r' => quoted.push_str("\\r"),
            '\t' => quoted.push_str("\\t"),
            _ => quoted.push(character),
        }
    }
    quoted.push('"');
    quoted
}

